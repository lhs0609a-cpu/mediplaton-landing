/** 은/는 조사 판정 — 마지막 한글 음절의 종성 유무로 결정 */
function josa(name) {
    const ch = name.charCodeAt(name.length - 1);
    if (ch < 0xac00 || ch > 0xd7a3) return '는';
    return (ch - 0xac00) % 28 === 0 ? '는' : '은';
}

